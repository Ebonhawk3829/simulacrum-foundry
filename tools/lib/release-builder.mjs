/**
 * Release Builder — assemble the two things a Foundry release contains.
 *
 * A Foundry installable release is just two assets: a manifest (`module.json`)
 * and an archive (`simulacrum.zip`). This module produces both from the working
 * tree, and it is the single definition of what "the release" means, so the
 * build script, the tests and the publisher cannot drift apart.
 *
 * Layout is taken from a released package rather than guessed. DAE's published
 * v14.0.16 archive wraps every path in a `dae/` folder and carries an explicit
 * entry for each directory; this reproduces that shape, because it is what
 * Foundry's installer has been observed to accept.
 *
 * Two deliberate deviations from upstream's packaging:
 *
 *   - The manifest in the archive is STAMPED. `download` must point at this
 *     release's own asset, otherwise a client following the update URL would
 *     fetch whichever archive the URL happened to name. `manifest` stays on the
 *     `releases/latest` URL, because Foundry only detects updates if that
 *     address is stable.
 *   - The build stamp is generated here rather than by a deploy script, so an
 *     installed copy can be told apart from another build in the console.
 */

import { readFileSync, readdirSync, statSync } from 'node:fs';
import { join, posix, relative, sep } from 'node:path';

import { createZip, readZip } from './zip.mjs';

/**
 * Directories and files that never belong in a release.
 *
 * These are matched against the path RELATIVE TO THE ROOT, never the bare
 * directory name. Matching by name would also drop `scripts/tools/`, which holds
 * the tools the module runs on — the archive would install and then fail on its
 * first import.
 */
export const EXCLUDED_ROOTS = Object.freeze([
  '.git',
  '.github',
  '.gemini',
  '.vscode',
  '.idea',
  'artifacts',
  'dist',
  'docs',
  'node_modules',
  'tests',
  'tools',
]);

/** Root entries that are included when present. */
export const INCLUDED_PATHS = Object.freeze([
  'module.json',
  'README.md',
  'CHANGELOG.md',
  'LICENSE',
  'scripts',
  'styles',
  'templates',
  'lang',
  'assets',
  'packs',
  // The dnd5e field reference the agent reads at runtime. Small enough to ship,
  // and shipping it means it cannot drift out of sync with the version that was
  // actually tested against this code.
  'reference',
]);

/**
 * Files that are present in the working tree but are not shippable.
 *
 * The demo GIF is withdrawn: it accounts for roughly 12 MB of a release whose
 * actual code is a fraction of that, and it is only referenced by this
 * repository's README, which is not part of the runtime module.
 */
export const WITHDRAWN_FILES = Object.freeze(['assets/simulacrum-demo.gif']);

/** Paths the archive must contain for the module to load at all. */
export const REQUIRED_FILES = Object.freeze([
  'module.json',
  'scripts/simulacrum.js',
  'styles/simulacrum.css',
  'templates/simulacrum/sidebar.hbs',
  'lang/en.json',
]);

/**
 * Read and parse a manifest, rejecting duplicate keys.
 *
 * `JSON.parse` silently keeps the last of a repeated key, so a manifest can hold
 * a dead value that never surfaces. This package's manifest shipped two
 * `description` keys, which is exactly the failure this catches.
 * @param {string} text
 * @param {string} [label]
 * @returns {object}
 */
export function parseManifest(text, label = 'module.json') {
  const duplicates = findDuplicateTopLevelKeys(text);
  if (duplicates.length > 0) {
    throw new Error(
      `${label} defines ${duplicates.map(k => `"${k}"`).join(', ')} more than once. ` +
        'JSON keeps only the last value, so the earlier one is dead. Remove the duplicate.'
    );
  }
  return JSON.parse(text);
}

/**
 * Find top-level keys that appear more than once in a JSON object literal.
 *
 * Scans line-by-line rather than parsing, because a parsed object has already
 * lost the information. Sufficient for a manifest, which is one key per line by
 * convention.
 * @param {string} text
 * @returns {string[]}
 */
export function findDuplicateTopLevelKeys(text) {
  const seen = new Set();
  const duplicates = new Set();
  // Top-level keys are indented by exactly two spaces in a formatted manifest.
  for (const match of text.matchAll(/^\s{2}"([^"]+)"\s*:/gm)) {
    if (seen.has(match[1])) duplicates.add(match[1]);
    seen.add(match[1]);
  }
  return [...duplicates];
}

/**
 * Build the `scripts/build-info.js` stamp.
 *
 * The entry point imports this inside a try/catch, so its absence is tolerated;
 * producing it means a running world reports which build is loaded, which is the
 * question a private fork asks most often.
 * @param {object} info
 * @returns {string}
 */
export function buildInfoSource({ version, tag, commit, date }) {
  return `/**
 * Generated by tools/build-release.mjs. Do not edit or commit.
 */
export const BUILD_HASH = ${JSON.stringify(commit ?? 'unknown')};
export const BUILD_VERSION = ${JSON.stringify(version)};
export const BUILD_TAG = ${JSON.stringify(tag ?? version)};
export const BUILD_DATE = ${JSON.stringify(date)};
`;
}

/**
 * Convert an absolute path to a forward-slashed path relative to the root.
 * @param {string} root
 * @param {string} absolute
 * @returns {string}
 */
function toRelative(root, absolute) {
  return relative(root, absolute).split(sep).join(posix.sep);
}

/**
 * Walk the working tree and collect shippable files.
 * @param {string} root - Repository root
 * @param {object} [options]
 * @param {string[]} [options.exclude] - Extra relative paths to skip
 * @returns {Array<{path: string, data: Buffer}>} Sorted by path
 */
export function collectFiles(root, { exclude = [] } = {}) {
  const excluded = new Set([...WITHDRAWN_FILES, ...exclude]);
  const files = [];

  const walk = absoluteDir => {
    const entriesInDir = readdirSync(absoluteDir, { withFileTypes: true }).sort((a, b) =>
      a.name.localeCompare(b.name)
    );

    for (const entry of entriesInDir) {
      const absolute = join(absoluteDir, entry.name);
      const path = toRelative(root, absolute);

      if (excluded.has(path)) continue;
      // Exclusions are matched against the path from the root, not the bare
      // directory name, so an excluded top-level "tools/" cannot also swallow
      // the module's own "scripts/tools/".
      if (entry.isDirectory() && EXCLUDED_ROOTS.includes(path)) continue;
      // The pack source form is not read at runtime; only the LevelDB is.
      if (path === 'packs/_source' || path.startsWith('packs/_source/')) continue;
      // LevelDB writes these while the pack is open; they are not content.
      if (/^packs\/.*\/(LOCK|LOG)$/.test(path)) continue;

      if (entry.isDirectory()) {
        walk(absolute);
      } else if (entry.isFile()) {
        files.push({ path, data: readFileSync(absolute) });
      }
    }
  };

  for (const included of INCLUDED_PATHS) {
    const absolute = join(root, included);
    const path = toRelative(root, absolute);
    if (excluded.has(path)) continue;

    let stats;
    try {
      stats = statSync(absolute);
    } catch {
      continue; // optional entry that this checkout does not have
    }

    if (stats.isDirectory()) walk(absolute);
    else files.push({ path, data: readFileSync(absolute) });
  }

  return files.sort((a, b) => a.path.localeCompare(b.path));
}

/**
 * Compare a built archive against the working tree it was built from.
 *
 * Nothing else catches a stale artifact. `dist/` is gitignored, so a release
 * built before the last edit sits there looking finished, and the failure is
 * silent: the upload succeeds and ships content that predates the release. This
 * was found the hard way, with a published 0.1.0 whose bundled CHANGELOG did not
 * contain the 0.1.0 entry.
 *
 * The stamped manifest and the generated build stamp are expected to differ from
 * the tree, so they are excluded and must be named explicitly.
 *
 * @param {Buffer} zip - A built archive
 * @param {string} root - Repository root to compare against
 * @param {object} [options]
 * @param {string[]} [options.ignore] - Root-relative paths expected to differ
 * @returns {{differing: string[], absent: string[]}} Paths that are stale
 */
export function checkArchiveFreshness(zip, root, { ignore = [] } = {}) {
  const skip = new Set(ignore);
  const differing = [];
  const absent = [];

  for (const entry of readZip(zip)) {
    if (entry.name.endsWith('/')) continue; // directory entry
    const path = entry.name.replace(/^[^/]+\//, '');
    if (skip.has(path)) continue;

    let disk;
    try {
      disk = readFileSync(join(root, path));
    } catch {
      absent.push(path);
      continue;
    }
    if (Buffer.compare(disk, entry.data) !== 0) differing.push(path);
  }

  return { differing, absent };
}

/**
 * Derive the directory entries an archive needs from the file paths in it.
 * @param {string[]} paths
 * @returns {string[]} Directory paths, each ending in "/", sorted
 */
export function directoryEntries(paths) {
  const dirs = new Set();
  for (const path of paths) {
    const parts = path.split('/');
    // The last part is the file itself; every ancestor is a directory.
    for (let i = 1; i < parts.length; i++) {
      dirs.add(`${parts.slice(0, i).join('/')}/`);
    }
  }
  return [...dirs].sort((a, b) => a.localeCompare(b));
}

/**
 * Stamp a manifest for a specific release.
 *
 * `manifest` is left on the stable `releases/latest` URL so update checks keep
 * working; `download` is pinned to this release, so a client installs the
 * archive this manifest came from.
 * @param {object} manifest - The repository manifest
 * @param {object} options
 * @param {string} options.version
 * @param {string} options.repoUrl
 * @returns {object} A new manifest object
 */
export function stampManifest(manifest, { version, repoUrl }) {
  const base = repoUrl.replace(/\/+$/, '');
  return {
    ...manifest,
    version,
    url: base,
    bugs: `${base}/issues`,
    changelog: `${base}/blob/main/CHANGELOG.md`,
    readme: `${base}/blob/main/README.md`,
    license: `${base}/blob/main/LICENSE`,
    manifest: `${base}/releases/latest/download/module.json`,
    download: `${base}/releases/download/${version}/${manifest.id}.zip`,
  };
}

/**
 * Assert that a set of archive paths is a coherent module.
 * @param {string[]} paths - Paths inside the archive, including the folder prefix
 * @param {string} folder - The folder prefix that was applied
 */
function assertCoherent(paths, folder) {
  const prefixed = new Set(paths);
  const missing = REQUIRED_FILES.map(f => `${folder}/${f}`).filter(f => !prefixed.has(f));

  if (missing.length > 0) {
    throw new Error(
      `The archive is missing files the module needs to load: ${missing.join(', ')}. ` +
        'A release without these installs but fails at run time.'
    );
  }

  // The module's own in-game tools must ship, or the agent has nothing to call.
  // This is checked explicitly because it is exactly what a name-based directory
  // exclusion gets wrong.
  if (!paths.some(p => p.startsWith(`${folder}/scripts/tools/`))) {
    throw new Error(
      `The archive has no ${folder}/scripts/tools/ entries. The builder tools are the point of ` +
        'this module; an exclusion rule is probably swallowing them.'
    );
  }

  const leaked = paths.filter(p =>
    ['node_modules/', 'tests/', 'tools/', '.github/', 'artifacts/', 'dist/'].some(prefix =>
      p.startsWith(`${folder}/${prefix}`)
    )
  );
  if (leaked.length > 0) {
    throw new Error(`Development paths leaked into the archive: ${leaked.slice(0, 5).join(', ')}`);
  }
}

/**
 * Build a complete release.
 * @param {object} options
 * @param {string} options.root - Repository root
 * @param {string} options.version - Version to release, e.g. "0.1.0"
 * @param {string} [options.repoUrl] - Overrides the manifest's own URL
 * @param {string} [options.commit] - Commit to record in the build stamp
 * @param {string} [options.date] - ISO date to record in the build stamp
 * @param {number} [options.mtime] - Fixed timestamp, for reproducible archives
 * @returns {{manifest: object, manifestJson: string, zip: Buffer, entries: Array<{name: string, data: Buffer}>, fileCount: number}}
 */
export function buildRelease({
  root,
  version,
  repoUrl,
  commit = 'unknown',
  date = new Date().toISOString(),
  mtime = Date.UTC(2020, 0, 1),
}) {
  if (!/^\d+\.\d+\.\d+$/.test(version ?? '')) {
    throw new Error(`Version "${version}" is not a three-part version such as 0.1.0.`);
  }

  const sourceManifest = parseManifest(readFileSync(join(root, 'module.json'), 'utf8'));
  const manifest = stampManifest(sourceManifest, {
    version,
    repoUrl: repoUrl ?? sourceManifest.url,
  });

  const folder = manifest.id;
  if (!folder) throw new Error('module.json has no "id"; the archive folder cannot be named.');

  const manifestJson = `${JSON.stringify(manifest, null, 2)}\n`;
  const contents = assembleContents({ root, manifestJson, version, commit, date });

  const withFolder = contents.map(file => ({ name: `${folder}/${file.path}`, data: file.data }));
  assertCoherent(
    withFolder.map(f => f.name),
    folder
  );

  const entries = buildEntries(withFolder, `${folder}/`);
  const zip = createZip(entries, { mtime });

  return {
    manifest,
    manifestJson,
    zip,
    entries,
    fileCount: contents.length,
    folder,
  };
}

/**
 * Assemble the contents of the archive as root-relative paths.
 *
 * The build stamp is generated rather than collected, and the repository
 * manifest is replaced by the stamped one.
 * @param {object} options
 * @returns {Array<{path: string, data: Buffer}>} Sorted by path
 */
function assembleContents({ root, manifestJson, version, commit, date }) {
  const stamp = buildInfoSource({ version, tag: version, commit, date });
  const collected = collectFiles(root, { exclude: ['scripts/build-info.js'] });

  return [
    { path: 'module.json', data: Buffer.from(manifestJson, 'utf8') },
    ...collected.filter(file => file.path !== 'module.json'),
    { path: 'scripts/build-info.js', data: Buffer.from(stamp, 'utf8') },
  ].sort((a, b) => a.path.localeCompare(b.path));
}

/**
 * Build the ordered entry list, adding the folder and directory entries.
 *
 * Sorting by name interleaves directory entries with their contents, so the
 * archive reads naturally when listed and two builds of the same tree are
 * byte-identical.
 * @param {Array<{name: string, data: Buffer}>} withFolder
 * @param {string} prefix - e.g. "simulacrum/"
 * @returns {Array<{name: string, data: Buffer}>}
 */
function buildEntries(withFolder, prefix) {
  const directories = directoryEntries(withFolder.map(f => f.name.replace(prefix, ''))).map(name => ({
    name: `${prefix}${name}`,
    data: Buffer.alloc(0),
  }));

  return [{ name: prefix, data: Buffer.alloc(0) }, ...withFolder, ...directories].sort((a, b) =>
    a.name.localeCompare(b.name)
  );
}
