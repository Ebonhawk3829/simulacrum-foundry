/**
 * Script authoring, and the flags it depends on.
 *
 * The flag half exists because `flags` in a build spec used to land in
 * `system.flags` — a place nothing reads — while the tool's own schema text claimed
 * module flags "are not lost". That is the same failure as the activities bug: a
 * build that reports success and does nothing. The tests below are mostly about
 * placement, because placement is the part that fails silently.
 *
 * The script half is the new capability. Its tests are about what is refused, not
 * about what runs: nothing here executes an authored script, and that is deliberate.
 */

import assert from 'node:assert/strict';
import { test } from 'node:test';

import { buildItemSystem, buildItemFlags } from '../../scripts/core/dnd5e/item-builders.js';
import {
  buildEmbeddedMacros,
  checkSyntax,
  findUnsafeWrite,
} from '../../scripts/core/dnd5e/script-authoring.js';

/* ------------------------------------------------------------------ flags --- */

test('a flags key never reaches the item system block', () => {
  // The bug: flags passed through to `system`, so flags.cat became system.flags.cat
  // and no module ever saw it.
  const system = buildItemSystem({ name: 'X', flags: { cat: { macros: {} } } }, 'x');
  assert.equal(system.flags, undefined, 'flags must not be written into system data');
  assert.equal(system.identifier, 'x', 'the identity still lands');
});

test('flags are collected at the item level', () => {
  const flags = buildItemFlags({ flags: { cat: { macros: {} }, 'midi-qol': { foo: 1 } } });
  assert.deepEqual(flags, { cat: { macros: {} }, 'midi-qol': { foo: 1 } });
});

test('an explicit flags argument wins over the spec', () => {
  const flags = buildItemFlags({ flags: { cat: { from: 'spec' } } }, { cat: { from: 'arg' } });
  assert.deepEqual(flags, { cat: { from: 'arg' } });
});

test('empty flags are null rather than an empty write', () => {
  // An empty object would be written as a flag update that erases nothing but
  // reports as a change; null lets the caller omit the key entirely.
  assert.equal(buildItemFlags({}), null);
  assert.equal(buildItemFlags({ flags: {} }), null);
  assert.equal(buildItemFlags({ flags: { cat: null } }), null);
});

test('a spec key that is not flags still passes through to system', () => {
  // The fix must not turn pass-through off for everything else.
  const system = buildItemSystem({ name: 'X', properties: ['mgc'] }, 'x');
  assert.deepEqual(system.properties, ['mgc']);
});

/* ---------------------------------------------------------------- scripts --- */

const VALID = {
  name: 'test-script',
  event: 'roll',
  pass: 'attackRoll',
  macro: 'const target = workflow.targets.first();',
};

test('a script becomes a CAT embedded macro entry', () => {
  const { entries, errors } = buildEmbeddedMacros([VALID], 'Reckless Attack', 'reckless-attack');
  assert.deepEqual(errors, []);
  assert.equal(entries.length, 1);

  const entry = entries[0];
  assert.equal(entry.name, 'test-script');
  assert.equal(entry.event, 'roll');
  assert.equal(entry.pass, 'attackRoll');
  // `macros` is ONE entry plus its filters, not a list of scripts.
  assert.equal(entry.macros.length, 1);
  assert.equal(entry.macros[0].priority, 0);
});

test('the authored script is attributed in a banner', () => {
  // A generated script found misbehaving has to be traceable to the build that made
  // it, or the only recourse is reading every flag on every item.
  const { entries } = buildEmbeddedMacros([VALID], 'Reckless Attack', 'reckless-attack');
  const macro = entries[0].macros[0].macro;
  assert.match(macro, /Generated by Simulacrum/);
  assert.match(macro, /reckless-attack/);
  assert.match(macro, /const target = workflow\.targets\.first\(\);/);
});

test('a script body cannot break out of the banner comment', () => {
  // The banner interpolates the item name, which came from the agent. A name
  // containing a newline and code would otherwise escape the comment.
  const { entries } = buildEmbeddedMacros([VALID], 'Evil\n*/ doThing(); /*', 'x');
  const macro = entries[0].macros[0].macro;
  assert.ok(!macro.split('\n').slice(0, 2).some(line => !line.startsWith('//')), 'the banner stays comments');
});

test('a script that does not parse is refused, and named', () => {
  const broken = { ...VALID, name: 'broken', macro: 'function ( {' };
  const { entries, errors } = buildEmbeddedMacros([broken], 'X', 'x');
  assert.equal(entries.length, 0);
  assert.equal(errors.length, 1);
  assert.match(errors[0], /broken/, 'the error names which script');
  assert.match(errors[0], /parse/i);
});

test('a script that writes to its own documents is ALLOWED', () => {
  // This is the rule an earlier version got wrong. Writing is what a script is for:
  // an effect that applies a condition has to create it, and 78 of Chris's Premades'
  // own 232 macros write this way. Refusing writes would refuse most of the feature.
  const applies = {
    ...VALID,
    name: 'applies',
    macro: 'await effectUtils.createEffects(actor, [effectData]);\nawait actor.update({ "system.hp.value": 1 });',
  };
  const { entries, errors } = buildEmbeddedMacros([applies], 'X', 'x');
  assert.deepEqual(errors, [], 'a scoped write is normal and must not be refused');
  assert.equal(entries.length, 1);
});

test('a script that writes to arbitrary collections is refused, and names the call', () => {
  // The only refusal left, and a narrow one: collection-level writes reach past the
  // documents in play, which is indistinguishable from a cached-data edit.
  const writer = { ...VALID, name: 'writer', macro: 'await Actor.updateDocuments([{ _id: "abc" }]);' };
  const { entries, errors } = buildEmbeddedMacros([writer], 'X', 'x');
  assert.equal(entries.length, 0);
  assert.match(errors[0], /updateDocuments/);
});

test('only the collection-level forms are caught', () => {
  // Scoped and plural forms differ by one word, and the check must tell them apart.
  const refused = [
    'await Actor.createDocuments([{ name: "x" }])',
    'await Actor.updateDocuments([])',
    'await Actor.deleteDocuments(["abc"])',
    'await actor.updateEmbeddedDocuments("Item", [])',
    'await actor.deleteEmbeddedDocuments("Item", [])',
  ];
  for (const call of refused) assert.ok(findUnsafeWrite(call), `expected ${call} to be refused`);

  const allowed = [
    'await actor.update({ name: "x" })',
    'item.update({ "system.uses.value": 1 })',
    'await actor.createEmbeddedDocuments("Item", [])',
    'await effectUtils.createEffects(actor, [data])',
    'await workflowUtils.completeItemUse(item)',
    'Hooks.callAll("customEvent")',
    'await item.setFlag("cat", "x", 1)',
  ];
  for (const call of allowed) assert.equal(findUnsafeWrite(call), null, `expected ${call} to be allowed`);
});

test('the unsafe-write check ignores comments', () => {
  // The banner says "Generated by Simulacrum", and an explanatory comment may
  // mention a refused call. Neither is a call.
  assert.equal(findUnsafeWrite('// never call Actor.updateDocuments() here\nconst x = 1;'), null);
  assert.equal(findUnsafeWrite('/* a comment about .deleteDocuments() */\nlet y = 2;'), null);
});

test('a script that never logs is warned about, not refused', () => {
  // A silent script is safe and useless: the console is half the evidence the test
  // loop has. A warning keeps it buildable while saying so.
  const silent = { ...VALID, name: 'silent', macro: 'const x = 1;' };
  const { entries, notes, errors } = buildEmbeddedMacros([silent], 'X', 'x');
  assert.deepEqual(errors, []);
  assert.equal(entries.length, 1);
  assert.match(notes[0], /log\(\)/);

  const loud = { ...VALID, name: 'loud', macro: 'log("thing happened");' };
  assert.deepEqual(buildEmbeddedMacros([loud], 'X', 'x').notes, []);
});

test('a missing required field is refused with the field named', () => {
  const { errors: noEvent } = buildEmbeddedMacros([{ pass: 'x', macro: 'a' }], 'X', 'x');
  assert.match(noEvent[0], /event/);

  const { errors: noPass } = buildEmbeddedMacros([{ event: 'roll', macro: 'a' }], 'X', 'x');
  assert.match(noPass[0], /pass/);

  const { errors: noMacro } = buildEmbeddedMacros([{ event: 'roll', pass: 'x' }], 'X', 'x');
  assert.match(noMacro[0], /macro/);
});

test('two scripts cannot share a name on one item', () => {
  // CAT warns and refuses the second, so catching it here gives a better message.
  const { entries, errors } = buildEmbeddedMacros([VALID, VALID], 'X', 'x');
  assert.equal(entries.length, 1);
  assert.match(errors[0], /used twice/);
});

test('a script with no name gets a derived one', () => {
  const { entries } = buildEmbeddedMacros(
    [{ event: 'roll', pass: 'attackRoll', macro: 'const a = 1;' }],
    'X',
    'my-ability'
  );
  assert.equal(entries[0].name, 'my-ability-roll-attackRoll');
});

test('a priority is kept when given and defaults otherwise', () => {
  const { entries } = buildEmbeddedMacros([
    { ...VALID, name: 'a', priority: 50 },
    { ...VALID, name: 'b' },
  ], 'X', 'x');
  assert.equal(entries[0].macros[0].priority, 50);
  assert.equal(entries[1].macros[0].priority, 0);
});

test('checkSyntax accepts valid code and rejects broken code', () => {
  assert.equal(checkSyntax('const a = 1;').ok, true);
  assert.equal(checkSyntax('const a = ;').ok, false);
  // Top-level await is valid in the wrapper, because the body is an async function.
  assert.equal(checkSyntax('await Promise.resolve();').ok, true);
});

test('nothing authored is executed while being checked', () => {
  // The check must parse without running. If it ran, this would set a global.
  delete globalThis.__simulacrum_ran;
  checkSyntax('globalThis.__simulacrum_ran = true;');
  assert.equal(globalThis.__simulacrum_ran, undefined, 'a build must not execute the code it writes');
});
