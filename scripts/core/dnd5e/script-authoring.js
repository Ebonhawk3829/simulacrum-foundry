/**
 * Script Authoring — CAT embedded macros, written onto an item.
 *
 * WHY THIS EXISTS
 *
 * Flags cover most abilities, but not all. Measured against Chris's Premades'
 * 631 premade items, 40% attach a macro whose logic cannot be expressed as flags:
 * reading combat state, branching on who did what, calling midi-qol's workflow
 * utilities. Nothing declarative covers `if (round !== 1) return; completeItemUse()`.
 *
 * The alternative to allowing this was escalating every such case to the user, which
 * is not a solution: if they could resolve it by hand, they would not have asked.
 *
 * WHY THIS IS NOT `run_javascript`
 *
 * That tool evaluates a string in the browser context and returns what it did. This
 * one does not evaluate anything at build time and does not run the script at all.
 * The script is stored as DATA — a string in `flags.cat.embeddedMacros` — and CAT
 * runs it later, in play, in the place CAT decides. So the build is still a write,
 * the script is visible in `document_read` and in the preview before it lands, and
 * the recorder in `ability-recorder.js` can observe the result like anything else.
 *
 * WHAT ACTUALLY PROTECTS AGAINST A BAD SCRIPT
 *
 * Not sandboxing — the script runs with full world access either way, and pretending
 * otherwise would be a false comfort. The protections are:
 *
 *   1. It cannot run at authoring time. Syntax is checked; behaviour is not executed.
 *   2. Syntax is checked before the write, so a script that cannot parse never lands.
 *   3. It is attributed. The first line of every authored script records that it was
 *      generated and for which ability, so a script found misbehaving is traceable.
 *   4. It is inspectable and reversible. It lives in flags, so it diffs, and removing
 *      it is a flag edit rather than a code change.
 *   5. The console line. Every script is given a `log()` helper that writes a single
 *      prefixed line, which is how the user's "I pressed it and this happened" report
 *      is joined up with what the script actually saw.
 *
 * The residual risk is a script that is syntactically valid and semantically wrong.
 * That is what the test loop is for, and it is why the item is flagged needs-testing
 * on write like any other build.
 */

/**
 * Anchored so a bare `.update(` cannot match: this is about the plural/global forms
 * that reach past the document they are on.
 */
const BLAST_RADIUS = new RegExp(
  '\\.\\s*('
    + 'createDocuments|updateDocuments|deleteDocuments'
    + '|updateEmbeddedDocuments|deleteEmbeddedDocuments'
    + ')\\s*\\('
);

/** The banner every authored script carries, so a generated script is identifiable. */
function banner(name, identifier) {
  return `// Generated by Simulacrum for "${shorthand(name)}" (identifier: ${shorthand(identifier)}).\n`
    + `// Not run at authoring time. Edit in the Cat Kit, or rebuild to replace it.\n`;
}

/** Keep one line of a string from breaking out of the comment banner. */
function shorthand(value) {
  return String(value ?? '').replace(/[\r\n]+/g, ' ').replace(/\*\//g, '').slice(0, 80);
}

/**
 * Validate one script without running it.
 *
 * `new Function` here parses and discards — it is called only to make the engine
 * report a syntax error, and the function is never invoked. That distinction is the
 * whole point: a build must not execute the code it is writing.
 * @param {string} source
 * @returns {{ok: true} | {ok: false, error: string}}
 */
export function checkSyntax(source) {
  try {
    // eslint-disable-next-line no-new-func
    new Function(`"use strict"; return (async function () {\n${source}\n});`);
    return { ok: true };
  } catch (err) {
    return { ok: false, error: err.message };
  }
}

/**
 * Find a call that would write to documents OTHER than the ones in play.
 *
 * This is deliberately narrow, and it is NOT a sandbox. A script that writes is
 * normal and necessary — an effect that applies a condition has to create it, and 78
 * of Chris's Premades' own 232 macros write through utilities like
 * `effectUtils.createEffects`. Refusing writes would refuse most uses of this
 * feature, which is why an earlier version of this check did not survive contact
 * with the corpus.
 *
 * What is refused is only the collection-level forms that reach past the documents
 * the script was handed. Those are indistinguishable from a cached-data edit, and
 * Foundry does not always fire the hooks that other modules depend on.
 *
 * The honest position: scope-level writes are allowed and cannot be sandboxed. The
 * real protections are that nothing runs at authoring time, a syntax error is caught
 * before the write, the script is attributed, it lives in flags so it can be read and
 * removed, and the test loop observes the result in play.
 * @param {string} source
 * @returns {string|null} The offending construct, or null when clean.
 */
export function findUnsafeWrite(source) {
  // Comments are stripped first so the banner and an explanatory comment cannot
  // trip the check.
  const code = source.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^\s*\/\/.*$/gm, '');
  const match = BLAST_RADIUS.exec(code);
  return match ? match[0].trim() : null;
}

/**
 * Check one entry's required fields, returning a reason or null.
 *
 * Split out because the field checks are the bulk of `buildEmbeddedMacros` and each
 * one only says which field is missing. Kept as a table so adding a required field is
 * one line rather than another branch.
 * @param {object} raw
 * @returns {string|null}
 */
function missingField(raw) {
  if (!raw.event || typeof raw.event !== 'string') return 'needs an "event" (when it runs)';
  if (!raw.pass || typeof raw.pass !== 'string') return 'needs a "pass" (the point in the event)';
  if (!raw.macro || typeof raw.macro !== 'string' || !raw.macro.trim()) {
    return 'needs a "macro" (the script body)';
  }
  return null;
}

/**
 * Turn the agent's script entries into CAT's `embeddedMacros` shaped data.
 *
 * CAT's flat form is `{ name, event, pass, macros: [{ macro, priority, ... }] }`,
 * confirmed against `flatToEmbedded` in CAT's own Cat Kit. The nested `macros` array
 * is not a list of scripts — it is one entry plus the filters for that entry, which
 * is why this always writes exactly one.
 * @param {object[]} scripts
 * @param {string} itemName
 * @param {string} identifier
 * @returns {{entries: object[], errors: string[], notes: string[]}}
 */
export function buildEmbeddedMacros(scripts, itemName, identifier) {
  const entries = [];
  const errors = [];
  const notes = [];
  const seen = new Set();

  const accept = (raw, label) => {
    const name = raw.name ?? `${identifier}-${raw.event}-${raw.pass}`;
    if (seen.has(name)) {
      errors.push(`${label}: the name "${name}" is used twice on this item`);
      return;
    }
    seen.add(name);

    const syntax = checkSyntax(raw.macro);
    if (!syntax.ok) {
      errors.push(`${label}: does not parse — ${syntax.error}`);
      return;
    }

    // Collection-level writes are refused; anything scoped to the documents in play
    // is allowed, because that is what an effect-applying script has to do.
    const unsafe = findUnsafeWrite(raw.macro);
    if (unsafe) {
      errors.push(
        `${label}: calls ${unsafe}, which writes to documents outside this ability. Use the scoped form `
          + '(actor.update, item.update, or a utility), so the change is limited to what is in play.'
      );
      return;
    }

    // A script that never logs is not wrong, but it is invisible: the user's report
    // and the console are the only evidence of what it saw.
    if (!/\blog\s*\(/.test(raw.macro)) {
      notes.push(`${label}: does not call log(), so there will be nothing in the console to read back`);
    }

    entries.push({
      name,
      event: raw.event,
      pass: raw.pass,
      macros: [
        {
          macro: banner(itemName, identifier) + raw.macro.replace(/\s+$/, '') + '\n',
          priority: Number.isFinite(raw.priority) ? raw.priority : 0,
        },
      ],
    });
  };

  for (const [index, raw] of (Array.isArray(scripts) ? scripts : []).entries()) {
    const label = raw?.name ?? `script ${index + 1}`;
    if (!raw || typeof raw !== 'object') { errors.push(`${label}: not an object`); continue; }

    const missing = missingField(raw);
    if (missing) { errors.push(`${label}: ${missing}`); continue; }

    accept(raw, label);
  }

  return { entries, errors, notes };
}

/**
 * The one-line log helper CAT provides to every embedded macro.
 *
 * Scripts should use it rather than `console.log`: it is what the user reads back
 * when they report what happened, and a silent script can only be debugged by
 * guessing. Exported for the reference documentation, not called by this module.
 */
export const LOG_HELPER = 'log';
